function applyLanguage(lang) {
  const currentLang = (lang === 'id') ? 'id' : 'en';
  try { localStorage.setItem('cac_lang', currentLang); } catch (e) {}
  document.documentElement.lang = currentLang;

  // Update button active state
  document.querySelectorAll('.lang-btn').forEach(btn => {
    if (btn.getAttribute('data-lang') === currentLang) {
      btn.classList.add('active');
    } else {
      btn.classList.remove('active');
    }
  });

  // Translate all [data-i18n]
  const dict = i18nDictionary[currentLang];
  if (!dict) return;

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (dict[key]) {
      el.textContent = dict[key];
    }
  });

  // Toggle dual language elements if any
  document.querySelectorAll('[data-lang-en]').forEach(el => {
    el.style.display = (currentLang === 'en') ? '' : 'none';
  });
  document.querySelectorAll('[data-lang-id]').forEach(el => {
    el.style.display = (currentLang === 'id') ? '' : 'none';
  });

  window.dispatchEvent(new CustomEvent('cac-language-changed', { detail: { lang: currentLang } }));
}

function initLanguageSwitcher() {
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.onclick = function(e) {
      e.preventDefault();
      const targetLang = this.getAttribute('data-lang');
      if (targetLang) applyLanguage(targetLang);
    };
  });

  let savedLang = 'en';
  try { savedLang = localStorage.getItem('cac_lang') || 'en'; } catch (e) {}
  applyLanguage(savedLang);
}

